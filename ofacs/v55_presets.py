def apply_v55_preset(args: Namespace) -> Namespace:
    """Apply a compact V5.5 preset to an argparse namespace in-place.

    ``off`` and ``custom`` leave explicit flags untouched.  Other presets set
    the small number of semantic options that define the ablation.  Low-level
    weights can still be overridden only by editing code or using hidden expert
    flags after this function is bypassed; standard scripts should not sweep
    them.
    """
    preset = str(getattr(args, "v55_preset", "off") or "off")
    if preset in {"off", "custom"}:
        return args
    if preset not in _PRESETS:
        raise ValueError(f"Unsupported --v55-preset={preset!r}; valid={V55_PRESET_CHOICES}")
    for key, value in _PRESETS[preset].items():
        if hasattr(args, key):
            setattr(args, key, value)
    return args

